const DICT: Record<UiLang, Record<UiKey, string>> = { en, tr };

export function translate(lang: UiLang, key: UiKey, vars?: Record<string, string | number>): string {
  let s = DICT[lang]?.[key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function pickLang(cookie?: string | null, acceptLanguage?: string | null): UiLang {
  if (cookie === "tr" || cookie === "en") return cookie;
  return /^\s*tr\b/i.test(acceptLanguage ?? "") || /(^|,)\s*tr/i.test(acceptLanguage ?? "") ? "tr" : "en";
}
